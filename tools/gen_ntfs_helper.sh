#!/bin/bash
# tools/gen_ntfs_helper.sh - build the NTFS disk-reader payload (#217) and embed
# it in EVO as projects/evoplayer/src/generated/evo_ntfs_helper_elf.c.
#
# EVO sends these bytes to the console's ELF loader when a USB disk may be
# there (projects/evoplayer/helpers/ntfs_helper.c says why). Run by
# scripts/build-evoplayer.sh and scripts/package-app.sh inside the container.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=projects/evoplayer/helpers/ntfs_helper.c
GEN=projects/evoplayer/src/generated
ELF=output/ntfs_helper.elf
SDK="${PS5_PAYLOAD_SDK:-/opt/ps5-payload-sdk}"
mkdir -p "${GEN}" output
"${SDK}/bin/prospero-clang" -O2 -Wall -Werror -o "${ELF}" "${SRC}" -lpthread
python3 - "${ELF}" "${GEN}/evo_ntfs_helper_elf.c" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
lines = ["/* generated by tools/gen_ntfs_helper.sh from helpers/ntfs_helper.c - do not edit */",
         "#include <stddef.h>",
         "const unsigned char evo_ntfs_helper_elf[] = {"]
for i in range(0, len(data), 20):
    lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
lines.append("};")
lines.append("const size_t evo_ntfs_helper_elf_len = %d;" % len(data))
open(sys.argv[2], "w", newline="\n").write("\n".join(lines) + "\n")
PY
echo "  ok ntfs helper payload: $(wc -c < "${ELF}") bytes -> ${GEN}/evo_ntfs_helper_elf.c"
