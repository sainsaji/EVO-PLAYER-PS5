#!/usr/bin/env python3
"""Embed yt-dlp's challenge solver (third_party/yt-dlp-ejs) into EVO.

Writes projects/evoplayer/addons/src/evo_ytjs_blob.c with lib.min.js and
core.min.js as byte arrays (each NUL-terminated, length excludes the NUL).
Re-run after replacing the two .js files with a newer yt-dlp-ejs release.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "yt-dlp-ejs"
OUT = ROOT / "projects" / "evoplayer" / "addons" / "src" / "evo_ytjs_blob.c"


def emit(name: str, data: bytes) -> str:
    lines = [f"const unsigned char {name}[] = {{"]
    body = data + b"\0"
    for i in range(0, len(body), 20):
        lines.append("    " + ",".join(str(b) for b in body[i:i + 20]) + ",")
    lines.append("};")
    lines.append(f"const unsigned long {name}_len = {len(data)}UL;")
    return "\n".join(lines) + "\n"


def main() -> None:
    lib = (SRC / "lib.min.js").read_bytes()
    core = (SRC / "core.min.js").read_bytes()
    text = (
        "/* GENERATED by tools/gen_ytjs_blob.py from third_party/yt-dlp-ejs - do not edit.\n"
        " * yt-dlp's YouTube challenge solver (Unlicense; bundles meriyah ISC and\n"
        " * astring MIT, see the header inside lib.min.js). */\n\n"
        + emit("evo_ytjs_lib", lib) + "\n" + emit("evo_ytjs_core", core)
    )
    OUT.write_bytes(text.encode("ascii"))
    print(f"wrote {OUT.relative_to(ROOT)} (lib {len(lib)} B, core {len(core)} B)")


if __name__ == "__main__":
    main()
